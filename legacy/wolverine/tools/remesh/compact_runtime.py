"""Offline endpoint reduction and complete runtime binding compaction.

Inputs are immutable gzip authoring archives, not included by the game build.
No decimation, remapping, or high-resolution safety skin runs in-game.
Run: python tools/remesh/compact_runtime.py generate|apply
"""
